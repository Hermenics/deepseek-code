  it('fences owned write retries and propagates non-busy SQLite errors with rollback', async () => {
    const s = database(), b = create(s), job = s.enqueue(b.id, 'Record the result')
    s.claim(b.id, 'worker')
    let calls = 0
    const write = () => { calls++; s.store.run('UPDATE bot_runs SET output = ? WHERE id = ?', 'must roll back', job.id); throw new Error('schema fixture') }
    await expect(s.writeOwned(job.id, 'worker', write)).rejects.toThrow('schema fixture')
    expect(calls).toBe(1); expect(s.getRun(job.id).output).toBe('')
    await expect(s.writeOwned(job.id, 'other-worker', write)).rejects.toThrow('ownership')
    await expect(s.writeOwned(job.id, 'worker', write, AbortSignal.abort(new Error('stopping fixture')))).rejects.toThrow('stopping fixture')
    expect(calls).toBe(1)
    s.store.exec(`CREATE TRIGGER fail_owned_event BEFORE INSERT ON events
      BEGIN SELECT RAISE(ABORT,'native event rejected'); END;`)
    await expect(s.writeOwned(job.id, 'worker', () => {
      s.store.run('UPDATE bot_runs SET output = ? WHERE id = ?', 'must also roll back', job.id)
      s.events(b.id).emit('FixtureEvent', {})
    })).rejects.toThrow('native event rejected')
    expect(s.getRun(job.id).output).toBe('')
    s.store.exec('DROP TRIGGER fail_owned_event')
    s.store.run('UPDATE bot_runs SET lease_until = ? WHERE id = ?', Date.now() - 1, job.id)
    await expect(s.writeOwned(job.id, 'worker', write)).rejects.toThrow('ownership')
    expect(calls).toBe(1)
  })

