/**
 * Generates src/generated/routes.ts from routes.json.
 *
 *   bun scripts/gen-routes.ts [outFile]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

interface RouteSpec { name: string; path: string }

const root = join(import.meta.dir, '..')
const specs = JSON.parse(readFileSync(join(root, 'routes.json'), 'utf8')) as RouteSpec[]

/** Compiles a route path into the regex source and parameter names the router uses. */
function compile(path: string): { pattern: string; params: string[] } {
  const params = [...path.matchAll(/:(\w+)/g)].map((m) => m[1]!)
  const pattern = '^' + path.replace(/:\w+/, '([^/]+)') + '$'
  return { pattern, params }
}

const entries = specs.map((spec) => {
  const { pattern, params } = compile(spec.path)
  return `  { name: ${JSON.stringify(spec.name)}, pattern: new RegExp(${JSON.stringify(pattern)}), params: ${JSON.stringify(params)} },`
})

const output = [
  '// DO NOT EDIT: generated by scripts/gen-routes.ts from routes.json. Run `bun run gen` after changing either.',
  "import type { CompiledRoute } from '../types'",
  '',
  'export const ROUTES: CompiledRoute[] = [',
  ...entries,
  ']',
  '',
].join('\n')

writeFileSync(process.argv[2] ?? join(root, 'src/generated/routes.ts'), output)
